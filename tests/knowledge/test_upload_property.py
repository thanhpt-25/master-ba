# Feature: local-rag, Property 3: Upload checks match the rule set
from hypothesis import given
from hypothesis import strategies as st

from masterba.knowledge.safety import (
    ARCHIVE_SUFFIXES,
    MAX_NAME_BYTES,
    SUPPORTED_TYPES,
    RefusalKind,
    check_upload,
)

_SIGNATURES = [
    b"PK\x03\x04",
    b"PK\x05\x06",
    b"7z\xbc\xaf\x27\x1c",
    b"\x1f\x8b",
    b"Rar!\x1a\x07",
    b"BZh91AY&SY",
    b"\xfd7zXZ\x00",
]
_stems = st.text(st.characters(codec="utf-8"), min_size=0, max_size=12) | st.sampled_from(
    ["", ".", "..", "a/b", "a\\b", "x\x01y", "あ" * 90]
)
_suffixes = st.sampled_from(
    [*SUPPORTED_TYPES, *(s.upper() for s in SUPPORTED_TYPES), *ARCHIVE_SUFFIXES, ".csv", ".exe", ""]
)
_contents = st.one_of(
    st.just(b""),
    st.text(max_size=50).map(str.encode),
    st.binary(max_size=50),
    st.builds(lambda sig, rest: sig + rest, st.sampled_from(_SIGNATURES), st.binary(max_size=20)),
    st.builds(lambda rest: b"%PDF-1.7" + rest, st.binary(max_size=20)),
    st.builds(lambda rest: b"\x00" * 257 + b"ustar" + rest, st.binary(max_size=10)),
)


def _name_bad(name: str) -> bool:
    return (
        name in ("", ".", "..")
        or "/" in name
        or "\\" in name
        or any(ord(c) < 0x20 or ord(c) == 0x7F for c in name)
        or len(name.encode("utf-8", "surrogatepass")) > MAX_NAME_BYTES
    )


def _plain_broken(suffix: str, data: bytes) -> set[RefusalKind]:
    broken: set[RefusalKind] = set()
    if any(data.startswith(s) for s in _SIGNATURES) or data[257:262] == b"ustar":
        broken.add(RefusalKind.ARCHIVE)
    if suffix == ".pdf":
        if not data.startswith(b"%PDF-"):
            broken.add(RefusalKind.MISMATCH)
    else:
        try:
            data.removeprefix(b"\xef\xbb\xbf").decode("utf-8")
        except UnicodeDecodeError:
            broken.add(RefusalKind.MISMATCH)
    return broken


def _broken_rules(name: str, data: bytes) -> set[RefusalKind]:
    """Reference predicate written from Requirement 2 (Office packages excluded)."""
    broken: set[RefusalKind] = set()
    if _name_bad(name):
        broken.add(RefusalKind.NAME)
    if not data:
        broken.add(RefusalKind.EMPTY)
    dot = name.rfind(".")
    suffix = name[dot:].lower() if dot >= 0 else ""
    if suffix in ARCHIVE_SUFFIXES:
        broken.add(RefusalKind.ARCHIVE)
    elif suffix not in SUPPORTED_TYPES:
        broken.add(RefusalKind.TYPE)
    elif suffix in (".xlsx", ".docx"):
        broken.add(RefusalKind.PACKAGE)  # generated bytes are never a valid package
    elif data:
        broken |= _plain_broken(suffix, data)
    return broken


@given(_stems, _suffixes, _contents)
def test_check_upload_matches_reference(stem: str, suffix: str, data: bytes) -> None:
    name = stem + suffix
    refusals = check_upload(name, data)
    broken = _broken_rules(name, data)
    assert len(refusals) <= 1
    assert bool(refusals) == bool(broken)
    if refusals:
        assert refusals[0].kind in broken
        if refusals[0].kind is RefusalKind.TYPE:
            assert all(t in refusals[0].message for t in SUPPORTED_TYPES)
